import { describe, expect, it } from "vitest";
import { fill, fmtCount, fmtDuration, fmtPercent, fmtSci } from "./format";

const NBSP = "\u00a0";
const YEAR = 365 * 86400;

describe("fmtDuration: человеческие единицы", () => {
  it.each([
    [7.09e-10, "0,71 нс"],
    [1e-5, "10 мкс"],
    [2e-4, "200 мкс"],
    [0.12194, "122 мс"],
    [2.195, "2,2 с"],
    [42.55, "43 с"],
    [100, "1,7 мин"],
    [200, "3,3 мин"],
    [42553, "12 ч"],
    [781250, "9 дней"],
    [133505, "1,5 дня"],
    [105 * 86400, "105 дней"],
    [28.7 * YEAR, "29 лет"],
    [YEAR, "1 год"],
    [2 * YEAR, "2 года"],
  ])("%s с → %s", (s, text) => {
    expect(fmtDuration(s)).toBe(text);
  });
});

describe("fmtCount: слова шкалы с согласованием", () => {
  it.each([
    [785, "785"],
    [1458, `1${NBSP}458`],
    [1e6, "1 миллион"],
    [3.545e6, "3,5 миллиона"],
    [1.8e7, "18 миллионов"],
    [1e10, "10 миллиардов"],
    [1.28e12, "1,3 триллиона"],
    [1e16, "10 квадриллионов"],
    [9.996e8, "1 миллиард"],
  ])("%s → %s", (n, text) => {
    expect(fmtCount(n)).toBe(text);
  });
  it("с 10¹⁸ — степенью десяти", () => {
    expect(fmtCount(4.53e20)).toBe("4,5·10²⁰");
  });
});

describe("fmtSci", () => {
  it("мантисса из двух цифр, показатель надстрочный", () => {
    expect(fmtSci(4.53e20)).toBe("4,5·10²⁰");
    expect(fmtSci(1e16)).toBe("10¹⁶");
    expect(fmtSci(9.98e13)).toBe("10¹⁴");
  });
});

describe("fmtPercent: шаг 0,5 п. п.", () => {
  it.each([
    [0.125, "12,5%"],
    [0.781, "78%"],
    [0.945, "94,5%"],
    [0.33, "33%"],
    [0.0047, "0,5%"],
  ])("%s → %s", (p, text) => {
    expect(fmtPercent(p)).toBe(text);
  });
});

describe("fill", () => {
  it("подставляет значения", () => {
    expect(fill("{a} из {b}", { a: "1", b: "2" })).toBe("1 из 2");
  });
  it("падает на отсутствующем ключе", () => {
    expect(() => fill("{a} и {b}", { a: "1" })).toThrow("{b}");
  });
});
